CREATE TABLE IF NOT EXISTS secrets (
    id UUID PRIMARY KEY,
    ciphertext TEXT NOT NULL,
    iv VARCHAR(64) NOT NULL,
    salt VARCHAR(64),
    has_passphrase BOOLEAN NOT NULL DEFAULT FALSE,
    max_views INT NOT NULL DEFAULT 1,
    remaining_views INT NOT NULL DEFAULT 1,
    creator_token VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_secrets_creator_token ON secrets(creator_token);
CREATE INDEX IF NOT EXISTS idx_secrets_expires_at ON secrets(expires_at);

CREATE TABLE IF NOT EXISTS access_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    secret_id UUID NOT NULL,
    creator_token VARCHAR(128) NOT NULL,
    event_type VARCHAR(32) NOT NULL,
    ip_address VARCHAR(64),
    user_agent VARCHAR(512),
    device_info VARCHAR(256),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_alerts_secret_id ON access_alerts(secret_id);
CREATE INDEX IF NOT EXISTS idx_alerts_creator_token ON access_alerts(creator_token);
